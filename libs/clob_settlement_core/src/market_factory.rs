    #[test]
    fn test_market_init_data_from_valid_config() {
        let env = Env::default();
        let config = MarketConfig {
            base: Address::generate(&env),
            quote: Address::generate(&env),
            lot_size: 100,
            tick_size: 100_000,
            max_tick: 1_000_000,
            fees: crate::MarketFeeConfig {
                taker_fee_rate: 100_000,
                maker_fee_rate: 50_000,
            },
            min_order_lots: 10,
            max_open_orders_per_trader: 100,
            status: MarketStatus::Active,
        };

        let init = MarketInitData::from_config(&env, &config).unwrap();
        
        assert_eq!(init.base, config.base);
        assert_eq!(init.quote, config.quote);
        assert_eq!(init.lot_size, 100);
        assert_eq!(init.tick_size, 100_000);
        assert_eq!(init.max_tick, 1_000_000);
        assert_eq!(init.taker_fee_rate, 100_000);
        assert_eq!(init.maker_fee_rate, 50_000);
        assert_eq!(init.min_order_lots, 10);
        assert_eq!(init.max_open_orders_per_trader, 100);
    }

