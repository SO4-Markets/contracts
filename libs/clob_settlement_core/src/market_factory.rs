use soroban_sdk::{Address, Env};
use crate::market_config::{MarketConfig, MarketStatus, MarketConfigError};

/// Deterministic MarketId derivation from base and quote tokens.
/// 
/// The MarketId is the canonical identifier for a market. It MUST be derived
/// deterministically from the pair so that:
/// - The same (base, quote) always produces the same ID
/// - (base, quote) and (quote, base) produce different IDs
/// - No collisions across different pairs
/// 
/// In Soroban, this is typically the market contract address itself,
/// but the ID is computed from a deterministic hash of (base, quote).
pub fn derive_market_id(env: &Env, base: &Address, quote: &Address) -> Address {
    // Stub: Real implementation computes a deterministic hash of (base, quote)
    // and derives the market contract address from it.
    // For now, return a placeholder that would be generated by the contract.
    
    // In a real Soroban contract, this would use:
    // env.invoke_contract(registry_id, "derive_id", (base, quote))
    // or a deterministic hash function on the pair.
    
    Address::from_contract_id(&env.crypto().sha256(&soroban_sdk::BytesN::from_array(env, &[0u8; 32])))
}

/// Market deployment error codes
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum DeploymentError {
    /// Market already exists for this pair
    MarketAlreadyExists = 1,
    /// Invalid market configuration
    InvalidConfiguration = 2,
    /// Deployment failed (contract instantiation error)
    DeploymentFailed = 3,
    /// Storage allocation failed
    StorageError = 4,
    /// Unauthorized (only admin can create markets)
    Unauthorized = 5,
}

impl From<MarketConfigError> for DeploymentError {
    fn from(err: MarketConfigError) -> Self {
        DeploymentError::InvalidConfiguration
    }
}

/// Immutable market initialization data.
/// 
/// This is stored once at market creation and never changes.
/// It includes the full configuration needed by the market contract.
#[derive(Clone, Debug)]
pub struct MarketInitData {
    /// Market ID (canonical identifier)
    pub id: Address,
    
    /// Base token
    pub base: Address,
    
    /// Quote token
    pub quote: Address,
    
    /// Base atoms per lot
    pub lot_size: u64,
    
    /// Price increment (scaled by PRICE_SCALE)
    pub tick_size: u64,
    
    /// Maximum tick index for this market
    pub max_tick: u64,
    
    /// Taker fee rate (fixed point over FEE_RATE_SCALE)
    pub taker_fee_rate: i128,
    
    /// Maker fee rate (fixed point over FEE_RATE_SCALE)
    pub maker_fee_rate: i128,
    
    /// Minimum order size in lots
    pub min_order_lots: u64,
    
    /// Maximum open orders per trader
    pub max_open_orders_per_trader: u32,
    
    /// Ledger at which the market was created
    pub created_ledger: u32,
}

impl MarketInitData {
    /// Create from a validated MarketConfig
    pub fn from_config(
        env: &Env,
        config: &MarketConfig,
    ) -> Result<Self, DeploymentError> {
        // Validate configuration before creating init data
        config.validate()?;
        
        let id = derive_market_id(env, &config.base, &config.quote);
        let current_ledger = env.ledger().sequence();
        
        Ok(MarketInitData {
            id,
            base: config.base.clone(),
            quote: config.quote.clone(),
            lot_size: config.lot_size,
            tick_size: config.tick_size,
            max_tick: config.max_tick,
            taker_fee_rate: config.fees.taker_fee_rate,
            maker_fee_rate: config.fees.maker_fee_rate,
            min_order_lots: config.min_order_lots,
            max_open_orders_per_trader: config.max_open_orders_per_trader,
            created_ledger: current_ledger,
        })
    }
}

/// Market deployment request from admin.
/// 
/// Admin submits this to create a new market. All fields are validated
/// before deployment.
pub struct DeploymentRequest {
    /// Base token
    pub base: Address,
    
    /// Quote token
    pub quote: Address,
    
    /// Base atoms per lot
    pub lot_size: u64,
    
    /// Price increment (scaled)
    pub tick_size: u64,
    
    /// Maximum tick
    pub max_tick: u64,
    
    /// Taker fee rate
    pub taker_fee_rate: i128,
    
    /// Maker fee rate
    pub maker_fee_rate: i128,
    
    /// Minimum order lots
    pub min_order_lots: u64,
    
    /// Max orders per trader
    pub max_open_orders_per_trader: u32,
}

impl DeploymentRequest {
    /// Validate the deployment request and create a config
    pub fn validate(self) -> Result<MarketConfig, DeploymentError> {
        let config = MarketConfig {
            base: self.base,
            quote: self.quote,
            lot_size: self.lot_size,
            tick_size: self.tick_size,
            max_tick: self.max_tick,
            fees: crate::MarketFeeConfig {
                taker_fee_rate: self.taker_fee_rate,
                maker_fee_rate: self.maker_fee_rate,
            },
            min_order_lots: self.min_order_lots,
            max_open_orders_per_trader: self.max_open_orders_per_trader,
            status: MarketStatus::Active,
        };
        
        config.validate()?;
        Ok(config)
    }
}

/// Market initialization state.
/// 
/// Stores immutable configuration and creation metadata.
/// Every market in the registry has exactly one instance of this,
/// created atomically at deployment time.
#[derive(Clone, Debug)]
pub struct MarketState {
    /// Immutable configuration
    pub config: MarketInitData,
    
    /// Whether the market has been initialized
    pub initialized: bool,
    
    /// Number of orders ever created (high water mark)
    pub order_sequence: u64,
    
    /// Number of traders with open orders
    pub active_traders: u32,
}

impl MarketState {
    /// Create a new market state from init data
    pub fn new(init: MarketInitData) -> Self {
        MarketState {
            config: init,
            initialized: true,
            order_sequence: 0,
            active_traders: 0,
        }
    }
}

/// Deployment result containing the created market and its metadata
pub struct DeploymentResult {
    /// Market ID (canonical identifier)
    pub market_id: Address,
    
    /// Base token
    pub base: Address,
    
    /// Quote token
    pub quote: Address,
    
    /// Full immutable configuration
    pub config: MarketInitData,
    
    /// Ledger at which the market was created
    pub created_ledger: u32,
}

/// Error result for deployment
pub type DeploymentOutcome<T> = Result<T, DeploymentError>;

